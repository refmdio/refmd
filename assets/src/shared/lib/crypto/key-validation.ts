function bytesEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

export function isValidX25519PublicKey(key: Uint8Array): boolean {
  if (key.length !== 32) return false;
  return !X25519_LOW_ORDER_POINTS.some((p) => bytesEqual(key, p));
}

export function isValidEd25519PublicKey(key: Uint8Array): boolean {
  if (key.length !== 32) return false;
  return !ED25519_SMALL_ORDER_POINTS.some((p) => bytesEqual(key, p));
}
